func fieldLabel(pdf *fpdf.Fpdf, x, w float64, label string) {
	pdf.SetFont("Helvetica", "B", 7.5)
	tc(pdf, colMuted)
	pdf.SetX(x)
	pdf.Cell(w, 4, label)
	pdf.Ln(4.8)
}

// prepareCode truncates lines longer than maxChars and strips trailing whitespace.
func prepareCode(code string, maxChars int) string {
	lines := strings.Split(code, "\n")
	out := make([]string, 0, len(lines))
	for _, line := range lines {
		line = strings.TrimRight(line, " \t")
		if len(line) > maxChars {
			line = line[:maxChars-3] + "..."
		}
		out = append(out, line)
	}
	// Remove trailing blank lines
	for len(out) > 0 && out[len(out)-1] == "" {
		out = out[:len(out)-1]
	}
	return strings.Join(out, "\n")
}

// prepareText strips trailing whitespace from each line.
func prepareText(text string) string {
	lines := strings.Split(text, "\n")
	out := make([]string, 0, len(lines))
	for _, l := range lines {
		out = append(out, strings.TrimRight(l, " \t"))
	}
	return strings.Join(out, "\n")
}

// estimateTextLines estimates how many lines MultiCell will produce.
// At 9.5pt Helvetica each char is ~2.1mm wide, so ~0.48 chars fit per mm.
func estimateTextLines(text string, widthMM, _ float64) int {
	const charsPerMM = 0.48
	limit := int(widthMM * charsPerMM)
	if limit < 10 {
		limit = 10
	}
	total := 0
	for _, para := range strings.Split(text, "\n") {
		if len(para) == 0 {
			total++
			continue
		}
		total += (len(para) + limit - 1) / limit
	}
	if total == 0 {
		return 1
	}
	return total
}

func shortenPath(path string, max int) string {
	if len(path) <= max {
		return path
	}
	return "..." + path[len(path)-(max-3):]
}

func shortenStr(s string, max int) string {
	if len(s) <= max {
		return s
	}
	return s[:max-3] + "..."
}

func countSeverities(findings []*types.Finding) map[string]int {
	c := map[string]int{"Critical": 0, "High": 0, "Medium": 0, "Low": 0}
	for _, f := range findings {
		c[f.Severity]++
	}
	return c
}

func riskRating(counts map[string]int) string {
	switch {
	case counts["Critical"] > 0:
		return "CRITICAL"
	case counts["High"] > 0:
		return "HIGH"
	case counts["Medium"] > 0:
		return "MEDIUM"
	default:
		return "LOW"
	}
}

func sortedFindings(findings []*types.Finding) []*types.Finding {
	order := map[string]int{"Critical": 0, "High": 1, "Medium": 2, "Low": 3}
	out := make([]*types.Finding, len(findings))
	copy(out, findings)
	sort.Slice(out, func(i, j int) bool {
		return order[out[i].Severity] < order[out[j].Severity]
	})
	return out
}

func formatNumber(n int) string {
	s := fmt.Sprintf("%d", n)
	if len(s) <= 3 {
		return s
	}
	result := make([]byte, 0, len(s)+(len(s)-1)/3)
	for i, c := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			result = append(result, ',')
		}
		result = append(result, byte(c))
	}
	return string(result)
}
